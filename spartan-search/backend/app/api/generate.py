import uuid

from fastapi import APIRouter, BackgroundTasks, Depends, Request
from sqlmodel import Session

from app.db.session import get_session
from app.db.tables import Job, Video
from app.errors import ApiError
from app.schemas.api import ErrorResponse, GenerateRequest, GeneratorModel, GeneratorStatus, UploadAccepted
from app.security import client_ip, generate_limiter, require_upload_key
from app.services import generation_service
from app.services.generation_service import GENERATED, GeneratorError
from app.worker import tasks
from app.worker.queue import enqueue

router = APIRouter(tags=["generate"])


@router.get("/generate/models", response_model=GeneratorStatus)
def generator_status() -> GeneratorStatus:
    try:
        models = generation_service.list_generator_models()
    except GeneratorError as exc:
        return GeneratorStatus(available=False, models=[], message=str(exc))
    return GeneratorStatus(available=True, models=[GeneratorModel(**m) for m in models])


@router.post(
    "/generate",
    status_code=202,
    response_model=UploadAccepted,
    responses={400: {"model": ErrorResponse}, 401: {"model": ErrorResponse}, 429: {"model": ErrorResponse},
               503: {"model": ErrorResponse}},
    dependencies=[Depends(require_upload_key)],
)
def generate(req: GenerateRequest, request: Request, background: BackgroundTasks,
             session: Session = Depends(get_session)) -> UploadAccepted:
    try:
        models = {m["id"]: m["label"] for m in generation_service.list_generator_models()}
    except GeneratorError as exc:
        raise ApiError(503, "generator_unavailable", str(exc))
    if req.model not in models:
        raise ApiError(400, "unknown_model", f"Choose one of: {', '.join(sorted(models))}.")
    generate_limiter.check(client_ip(request))

    prompt = " ".join(req.prompt.split())
    video_id = f"gen_{uuid.uuid4().hex[:12]}"
    job_id = f"job_{uuid.uuid4().hex[:12]}"
    session.add(Video(
        id=video_id, collection=GENERATED, title=prompt[:120], source=f"Generated by {models[req.model]}",
        license="Synthetic clip generated on this site", captions=prompt, status="queued",
    ))
    session.add(Job(id=job_id, video_id=video_id, kind="generate", status="queued", progress=0.0,
                    step_detail="Waiting for the GPU"))
    session.commit()
    enqueue(background, tasks.generate_video, video_id, prompt, req.model, req.seed, job_id)
    return UploadAccepted(video_id=video_id, job_id=job_id)
